"""Deterministic provenance signal detectors."""

from __future__ import annotations

import re

from reasonledger_core.models.provenance import (
    ChangeProvenanceInput,
    ProvenanceFinding,
    SignalConfidence,
    SignalType,
)

# Known AI co-author trailer markers (case-insensitive match on name portion).
COAUTHOR_AI_MARKERS: tuple[str, ...] = (
    "claude",
    "copilot",
    "cursor",
    "aider",
    "devin",
    "codex",
    "chatgpt",
    "openai",
    "anthropic",
)

# Known bot/agent GitHub logins (lowercase).
KNOWN_BOT_LOGINS: frozenset[str] = frozenset(
    {
        "github-copilot[bot]",
        "dependabot[bot]",
        "devin-ai-integration[bot]",
        "cursor[bot]",
    }
)

# Branch prefixes indicating likely AI tooling (weak signal).
WEAK_BRANCH_PREFIXES: tuple[str, ...] = ("cursor/", "claude/", "codex/", "aider/")

# PR/issue labels treated as explicit AI-assisted markers (strong).
AI_ASSISTED_LABELS: frozenset[str] = frozenset(
    {
        "ai-assisted",
        "copilot",
        "ai-generated",
        "claude",
        "cursor",
    }
)

# Generated-code sentinel patterns in diff hunks (strong).
GENERATED_MARKER_PATTERN = re.compile(
    r"(?i)(generated by|auto-generated|@generated|do not edit.*generated)",
)

# Weak commit-message tool signatures.
# A bare tool name is not a signal — "close the db cursor" is not AI provenance.
# Require an explicit authoring qualifier next to the tool name.
COMMIT_MESSAGE_TOOL_PATTERN = re.compile(
    r"(?i)\b(?:generated|written|authored|assisted|created)\s+(?:by|with|using)\s+"
    r"(copilot|claude|cursor|aider|codex|chatgpt)\b"
    r"|\b(copilot|claude|cursor|aider|codex)\s*[-–]\s*(?:generated|authored|assisted)\b",
)

COAUTHOR_TRAILER_PATTERN = re.compile(
    r"(?i)^co-authored-by:\s*(.+)$",
    re.MULTILINE,
)


def _is_ai_coauthor_trailer(trailer_line: str) -> bool:
    match = COAUTHOR_TRAILER_PATTERN.match(trailer_line.strip())
    if not match:
        return False
    name_portion = match.group(1).lower()
    return any(marker in name_portion for marker in COAUTHOR_AI_MARKERS)


def detect_coauthor_trailers(commit_message: str | None) -> list[ProvenanceFinding]:
    if not commit_message:
        return []
    findings: list[ProvenanceFinding] = []
    for line in commit_message.splitlines():
        if _is_ai_coauthor_trailer(line):
            findings.append(
                ProvenanceFinding(
                    signal_type=SignalType.COAUTHOR_TRAILER,
                    confidence=SignalConfidence.STRONG,
                    evidence_pointer=line.strip(),
                )
            )
    return findings


def detect_bot_author(
    author_login: str | None,
    committer_login: str | None,
) -> list[ProvenanceFinding]:
    findings: list[ProvenanceFinding] = []
    for login in (author_login, committer_login):
        if login and login.lower() in KNOWN_BOT_LOGINS:
            findings.append(
                ProvenanceFinding(
                    signal_type=SignalType.BOT_AUTHOR,
                    confidence=SignalConfidence.STRONG,
                    evidence_pointer=login,
                )
            )
    return findings


def detect_agent_pr_author(pr_author_login: str | None) -> list[ProvenanceFinding]:
    if not pr_author_login:
        return []
    if pr_author_login.lower() in KNOWN_BOT_LOGINS:
        return [
            ProvenanceFinding(
                signal_type=SignalType.AGENT_PR_AUTHOR,
                confidence=SignalConfidence.STRONG,
                evidence_pointer=pr_author_login,
            )
        ]
    return []


def detect_explicit_labels(labels: list[str]) -> list[ProvenanceFinding]:
    findings: list[ProvenanceFinding] = []
    for label in labels:
        normalized = label.strip().lower()
        if normalized in AI_ASSISTED_LABELS:
            findings.append(
                ProvenanceFinding(
                    signal_type=SignalType.EXPLICIT_LABEL,
                    confidence=SignalConfidence.STRONG,
                    evidence_pointer=label,
                )
            )
    return findings


def detect_generated_markers(diff_hunks: list[str]) -> list[ProvenanceFinding]:
    findings: list[ProvenanceFinding] = []
    for hunk in diff_hunks:
        match = GENERATED_MARKER_PATTERN.search(hunk)
        if match:
            findings.append(
                ProvenanceFinding(
                    signal_type=SignalType.GENERATED_MARKER,
                    confidence=SignalConfidence.STRONG,
                    evidence_pointer=match.group(0),
                )
            )
    return findings


def detect_branch_name(branch_name: str | None) -> list[ProvenanceFinding]:
    if not branch_name:
        return []
    lowered = branch_name.lower()
    for prefix in WEAK_BRANCH_PREFIXES:
        if lowered.startswith(prefix):
            return [
                ProvenanceFinding(
                    signal_type=SignalType.BRANCH_NAME,
                    confidence=SignalConfidence.WEAK,
                    evidence_pointer=branch_name,
                )
            ]
    return []


def detect_commit_message_pattern(commit_message: str | None) -> list[ProvenanceFinding]:
    if not commit_message:
        return []
    match = COMMIT_MESSAGE_TOOL_PATTERN.search(commit_message)
    if match:
        return [
            ProvenanceFinding(
                signal_type=SignalType.COMMIT_MESSAGE_PATTERN,
                confidence=SignalConfidence.WEAK,
                evidence_pointer=match.group(0).strip(),
            )
        ]
    return []


def detect_provenance_signals(change: ChangeProvenanceInput) -> list[ProvenanceFinding]:
    """Run all deterministic provenance detectors for a change."""
    findings: list[ProvenanceFinding] = []
    findings.extend(detect_coauthor_trailers(change.commit_message))
    findings.extend(detect_bot_author(change.commit_author_login, change.commit_committer_login))
    findings.extend(detect_agent_pr_author(change.pr_author_login))
    findings.extend(detect_explicit_labels(change.pr_labels))
    findings.extend(detect_generated_markers(change.diff_hunks))
    findings.extend(detect_branch_name(change.branch_name))
    findings.extend(detect_commit_message_pattern(change.commit_message))
    return findings
