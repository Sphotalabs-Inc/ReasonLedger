"""Phase 1 provenance detector golden tests."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
from reasonledger_core.models.provenance import ChangeProvenanceInput, ProvenanceStatus
from reasonledger_core.provenance.classify import classify_provenance

FIXTURES = Path(__file__).resolve().parents[3] / "fixtures" / "golden" / "provenance" / "cases.json"


def _load_cases() -> list[dict[str, Any]]:
    cases: list[dict[str, Any]] = json.loads(FIXTURES.read_text("utf-8"))
    return cases


@pytest.mark.phase_1
@pytest.mark.parametrize("case", _load_cases(), ids=lambda c: c["id"])
def test_provenance_golden_cases(case: dict[str, Any]) -> None:
    change = ChangeProvenanceInput.model_validate(case["input"])
    status, findings = classify_provenance(change)

    assert status == ProvenanceStatus(case["expected_status"])
    assert len(findings) == len(case["expected_signals"])
    for finding, expected in zip(findings, case["expected_signals"], strict=True):
        assert finding.signal_type.value == expected["signal_type"]
        assert finding.confidence.value == expected["confidence"]


@pytest.mark.phase_1
def test_commit_pattern_no_false_positive_on_db_cursor() -> None:
    from reasonledger_core.provenance.detectors import detect_commit_message_pattern

    for msg in (
        "fix cursor leak in the pagination query",
        "revert: close db cursor properly",
        "add claude shannon entropy metric",
    ):
        assert detect_commit_message_pattern(msg) == []


@pytest.mark.phase_1
def test_commit_pattern_still_matches_declared_authorship() -> None:
    from reasonledger_core.provenance.detectors import detect_commit_message_pattern

    for msg in (
        "generated by Claude",
        "co-authored with Copilot",
        "cursor-generated migration",
    ):
        assert detect_commit_message_pattern(msg), msg
